export function skinServiceLanguage(value: string): SkinServiceLanguage {
  return skinServiceLanguages.includes(value as SkinServiceLanguage)
    ? value as SkinServiceLanguage
    : "zh-CN";
}

export function skinText(
  language: SkinServiceLanguage,
  key: SkinTextKey,
  values: Record<string, string | number> = {},
) {
  let result = copy[language][key];
  for (const [name, value] of Object.entries(values)) {
    result = result.replaceAll(`{${name}}`, String(value));
  }
  return result;
}
